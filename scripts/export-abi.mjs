// Regenerates packages/shared/src/abi/*.ts from Foundry build output.
// Run after any contract interface change: `pnpm contracts:build && pnpm abi`.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const OUT = "packages/contracts/out";
const DEST = "packages/shared/src/abi";
const contracts = [
  ["MerchantCredit.sol", "MerchantCredit", "merchantCreditAbi"],
  ["SwayMarketplace.sol", "SwayMarketplace", "swayMarketplaceAbi"],
  ["MockUSDC.sol", "MockUSDC", "mockUsdcAbi"],
];

const index = [];
for (const [file, name, exportName] of contracts) {
  const p = join(OUT, file, `${name}.json`);
  if (!existsSync(p)) throw new Error(`${p} missing — run pnpm contracts:build first`);
  const { abi } = JSON.parse(readFileSync(p, "utf8"));
  writeFileSync(
    join(DEST, `${name}.ts`),
    `// GENERATED by scripts/export-abi.mjs — do not edit by hand.\nexport const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  index.push(`export { ${exportName} } from "./${name}.ts";`);
}
writeFileSync(join(DEST, "index.ts"), `// GENERATED\n${index.join("\n")}\n`);
console.log(`Exported ${contracts.length} ABIs to ${DEST}`);
